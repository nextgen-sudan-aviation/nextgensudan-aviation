-- Sudan Aviation NextGen initial database schema. Run in Supabase SQL Editor.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Aviation Member',
  role text not null default 'member' check (role in ('member','admin')),
  created_at timestamptz not null default now()
);
create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 2000),
  created_at timestamptz not null default now()
);
create table if not exists public.forum_posts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  category text not null,
  title text not null check (char_length(title) between 3 and 180),
  body text not null check (char_length(body) between 1 and 12000),
  created_at timestamptz not null default now()
);
alter table public.profiles enable row level security;
alter table public.chat_messages enable row level security;
alter table public.forum_posts enable row level security;
create policy "Profiles readable by authenticated" on public.profiles for select to authenticated using (true);
create policy "Users can create own profile" on public.profiles for insert to authenticated with check (auth.uid() = id);
create policy "Users update own profile" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);
create policy "Chat readable by authenticated" on public.chat_messages for select to authenticated using (true);
create policy "Users send own chat messages" on public.chat_messages for insert to authenticated with check (auth.uid() = user_id);
create policy "Users can delete own chat messages" on public.chat_messages for delete to authenticated using (auth.uid() = user_id);
create policy "Posts readable by authenticated" on public.forum_posts for select to authenticated using (true);
create policy "Users create own posts" on public.forum_posts for insert to authenticated with check (auth.uid() = user_id);
create policy "Users update own posts" on public.forum_posts for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users delete own posts" on public.forum_posts for delete to authenticated using (auth.uid() = user_id);

-- Automatically create profile after signup. Role is always 'member'; never trust user metadata for admin.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.profiles (id, display_name, role)
  values (new.id, coalesce(new.raw_user_meta_data->>'display_name','Aviation Member'), 'member');
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

